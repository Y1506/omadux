#!/usr/bin/env python3
"""scripts/rewrite-imports.py — Rewrite DUX import qs.* into relative directory imports
and generate valid qmldir files for each submodule directory.
"""

import os
import re
import sys

QUICKSHELL_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "quickshell")
)

SUBMODULE_MAP = {
    "qs.Common": "Common",
    "qs.Services": "Services",
    "qs.DCommon": "DCommon",
    "qs.Widgets": "Widgets",
    "qs.Modals": "Modals",
    "qs.Modules": "Modules",
}


def generate_qmldirs(root_dir):
    """Generates qmldir for every directory under root_dir that contains .qml files."""
    for dirpath, dirnames, filenames in os.walk(root_dir):
        qml_files = [f for f in filenames if f.endswith(".qml")]
        if not qml_files:
            continue

        entries = ["# Generated by rewrite-imports.py\n"]
        for f in sorted(qml_files):
            full_path = os.path.join(dirpath, f)
            type_name = os.path.splitext(f)[0]
            is_singleton = False
            try:
                with open(full_path, "r", encoding="utf-8", errors="ignore") as qf:
                    for line in qf:
                        stripped = line.strip()
                        if not stripped or stripped.startswith("//") or stripped.startswith("/*"):
                            continue
                        if stripped.startswith("pragma Singleton"):
                            is_singleton = True
                            break
                        if stripped.startswith("import") or "{" in stripped:
                            break
            except Exception as e:
                print(f"Warning: could not read {full_path}: {e}", file=sys.stderr)

            if is_singleton:
                entries.append(f"singleton {type_name} 1.0 {f}\n")
            else:
                entries.append(f"{type_name} 1.0 {f}\n")

        qmldir_path = os.path.join(dirpath, "qmldir")
        with open(qmldir_path, "w", encoding="utf-8") as qmldir:
            qmldir.writelines(entries)
        print(f"Generated {os.path.relpath(qmldir_path, root_dir)}")


def rewrite_file_imports(filepath, root_dir):
    """Rewrites forbidden qs.* imports in a single .qml file."""
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()
    except Exception as e:
        print(f"Error reading {filepath}: {e}", file=sys.stderr)
        return

    file_dir = os.path.dirname(filepath)
    modified = False

    def replace_import(match):
        nonlocal modified
        full_match = match.group(0)
        prefix = match.group(1)  # whitespace
        imported = match.group(2)  # e.g. qs.Common or qs.Common.settings
        suffix = match.group(3) or ""  # e.g. " as DCommon" or ""

        # NEVER touch qs.Core, qs.Ui, or qs.Commons (Omarchy's)
        if imported in ("qs.Core", "qs.Ui", "qs.Commons") or imported.startswith("qs.Core.") or imported.startswith("qs.Ui."):
            return full_match

        # Match against known roots
        target_subpath = None
        for root_key, target_folder in SUBMODULE_MAP.items():
            if imported == root_key:
                target_subpath = target_folder
                break
            elif imported.startswith(root_key + "."):
                remainder = imported[len(root_key) + 1 :].replace(".", "/")
                target_subpath = f"{target_folder}/{remainder}"
                break

        if not target_subpath:
            return full_match

        target_dir = os.path.join(root_dir, target_subpath)
        rel_path = os.path.relpath(target_dir, file_dir)
        if not rel_path.startswith("."):
            rel_path = "./" + rel_path

        modified = True
        return f'{prefix}import "{rel_path}"{suffix}'

    # Regex matching: import qs.Foo.Bar (as Alias)?
    import_pattern = re.compile(
        r"^([ \t]*)import[ \t]+(qs\.[A-Za-z0-9_.]+)([ \t]+as[ \t]+[A-Za-z0-9_]+)?",
        re.MULTILINE,
    )
    new_content = import_pattern.sub(replace_import, content)

    if modified:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(new_content)


def process_tree(root_dir):
    generate_qmldirs(root_dir)

    for dirpath, _, filenames in os.walk(root_dir):
        for f in filenames:
            if f.endswith(".qml") or f.endswith(".js"):
                rewrite_file_imports(os.path.join(dirpath, f), root_dir)


if __name__ == "__main__":
    target = QUICKSHELL_DIR
    if len(sys.argv) > 1:
        target = sys.argv[1]
    print(f"Rewriting imports under {target}...")
    process_tree(target)
    print("✓ Finished rewriting imports.")
